"""
    Solvers: High-Accuracy Adaptive Numerical Integration Suite
"""

abstract type AbstractODESolver end

"""
    ODESolution

Container for numerical trajectories generated by ODE solvers.
"""
struct ODESolution
    t::Vector{Float64}
    u::Vector{Vector{Float64}}
    retcode::Symbol
    n_steps::Int
    n_fevals::Int
    n_rejected::Int
end

# Helper to convert vector of vectors to 2D matrix (time-steps × variables)
function to_matrix(sol::ODESolution)
    n_steps = length(sol.u)
    if n_steps == 0
        return Matrix{Float64}(undef, 0, 0)
    end
    n_vars = length(sol.u[1])
    mat = Matrix{Float64}(undef, n_steps, n_vars)
    for i in 1:n_steps
        mat[i, :] = sol.u[i]
    end
    return mat
end
